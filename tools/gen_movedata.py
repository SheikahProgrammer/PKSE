#!/usr/bin/env python3
"""Generate include/Names/MoveData.h and src/Names/MoveData.cpp from dexfacts.tsv.gz.

Provides per-move type, category (Physical/Special/Status), base power, and accuracy
for all Pokémon moves across Gen 1-9.
"""
import gzip
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_PATH = os.path.join(ROOT, "tools", "dexfacts.tsv.gz")
OUT_H = os.path.join(ROOT, "include", "Names", "MoveData.h")
OUT_CPP = os.path.join(ROOT, "src", "Names", "MoveData.cpp")

HEADER_CONTENT = """// AUTO-GENERATED by tools/gen_movedata.py from tools/dexfacts.tsv.gz.
// DO NOT EDIT BY HAND -- rerun the generator instead.
#ifndef NAMES_MOVE_DATA_H
#define NAMES_MOVE_DATA_H

#include <cstdint>

namespace Names
{
    struct MoveData
    {
        uint8_t type;       // 0-17 (Normal..Fairy; 18=Stellar)
        uint8_t category;   // 0=Status, 1=Physical, 2=Special
        uint8_t power;      // 0-250 (0 = status/variable power)
        uint8_t accuracy;   // 0-100 (0 = never misses or status)
    };

    MoveData getMoveData(uint16_t moveId);
}

#endif // NAMES_MOVE_DATA_H
"""

def main():
    if not os.path.exists(DATA_PATH):
        sys.exit(f"Error: dataset {DATA_PATH} not found.")

    moves = {}
    with gzip.open(DATA_PATH, "rt", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().split("\t")
            if parts and parts[0] == "M" and len(parts) >= 6:
                mid = int(parts[1])
                mtype = int(parts[2])
                mcat = int(parts[3])
                mpower = int(parts[4])
                macc = int(parts[5])
                moves[mid] = (mtype, mcat, mpower, macc)

    max_id = max(moves.keys()) if moves else 0
    print(f"Loaded {len(moves)} moves from {DATA_PATH} (max move ID: {max_id}).")

    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write(HEADER_CONTENT)
    print(f"Wrote {OUT_H}")

    lines = [
        "// AUTO-GENERATED by tools/gen_movedata.py from tools/dexfacts.tsv.gz.",
        "// DO NOT EDIT BY HAND -- rerun the generator instead.",
        '#include "Names/MoveData.h"',
        "",
        "namespace Names",
        "{",
        "    static constexpr MoveData MOVE_DATA_TABLE[] = {",
        "        {0, 0, 0, 0}, // 0: None",
    ]

    for mid in range(1, max_id + 1):
        if mid in moves:
            t, c, p, a = moves[mid]
            lines.append(f"        {{{t}, {c}, {p}, {a}}}, // {mid}")
        else:
            lines.append(f"        {{0, 0, 0, 0}}, // {mid}")

    lines.extend([
        "    };",
        "",
        "    MoveData getMoveData(uint16_t moveId)",
        "    {",
        "        if (moveId < sizeof(MOVE_DATA_TABLE) / sizeof(MOVE_DATA_TABLE[0]))",
        "            return MOVE_DATA_TABLE[moveId];",
        "        return MoveData{0, 0, 0, 0};",
        "    }",
        "}",
        "",
    ])

    with open(OUT_CPP, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT_CPP}")

if __name__ == "__main__":
    main()
