#!/usr/bin/env python3
"""Generate include/Pokemon/LevelUpTable.h + src/Pokemon/LevelUpTable.cpp from PKHeX's
per-game level-up learnsets (Resources/byte/levelup/lvlmove_*.pkl), Gen 3 onward.

WHY: LearnsetTable answers "can it ever know this move" (a bitset, levels discarded). Building
a Pokemon the way the games do needs the levels: a wild Pokemon knows the last four moves it
learned by levelling, at the level it was met. That is what getWildMoveset() returns.

Format: BinLinkerAccessor16 container; entry i is move[count] (u16) then level[count] (u8),
indexed by that game's PersonalTable.GetFormIndex(species, form) -- which PersonalRecord already
mirrors at runtime (formCount + formIndex), so only the raw entries are emitted here.

Gen 1/2 are not covered: PKSE has no encounter data before Gen 3 either.

Run:  python tools/gen_levelup.py
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pkhex_source import pkhex_path, pkhex_ref  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (group enum, PKHeX level-up resource). Emerald's table serves the Ruby/Sapphire/Emerald group.
GROUPS = [
    ("RSE", "lvlmove_e"), ("FRLG", "lvlmove_fr"), ("DP", "lvlmove_dp"), ("PT", "lvlmove_pt"),
    ("HGSS", "lvlmove_hgss"), ("BW", "lvlmove_bw"), ("B2W2", "lvlmove_b2w2"), ("XY", "lvlmove_xy"),
    ("ORAS", "lvlmove_ao"), ("SM", "lvlmove_sm"), ("USUM", "lvlmove_uu"), ("GG", "lvlmove_gg"),
    ("SWSH", "lvlmove_swsh"), ("BDSP", "lvlmove_bdsp"), ("PLA", "lvlmove_la"), ("SV", "lvlmove_sv"),
    ("ZA", "lvlmove_za"),
]


def entries(data):
    count = struct.unpack_from("<H", data, 2)[0]
    return [data[s:e] for (s, e) in (struct.unpack_from("<HH", data, 4 + i * 2) for i in range(count))]


def main():
    header = os.path.join(ROOT, "include", "Pokemon", "LevelUpTable.h")
    source = os.path.join(ROOT, "src", "Pokemon", "LevelUpTable.cpp")
    out = ["// GENERATED by tools/gen_levelup.py from PKHeX level-up learnsets. Do not edit.\n",
           '#include "Pokemon/LevelUpTable.h"\n\n#include <algorithm>\n\n#include "Pokemon/PersonalRecord.h"\n\n',
           "namespace Pokemon\n{\n    namespace\n    {\n"]
    table_rows = []
    total = 0
    for group, resource in GROUPS:
        with open(pkhex_path("Resources/byte/levelup/" + resource + ".pkl"), "rb") as fh:
            blobs = entries(fh.read())
        flat, starts = [], []
        for blob in blobs:
            starts.append(len(flat))
            n = len(blob) // 3
            moves = struct.unpack_from("<%dH" % n, blob, 0) if n else ()
            levels = blob[2 * n:3 * n]
            flat.extend(zip(moves, levels))
        starts.append(len(flat))
        total += len(flat)
        out.append(f"        const LevelUpMove MOVES_{group}[] = {{\n")
        for i in range(0, len(flat), 8):
            out.append("            " + " ".join("{%d, %d}," % p for p in flat[i:i + 8]) + "\n")
        out.append("        };\n")
        out.append(f"        const uint32_t STARTS_{group}[] = {{\n")
        for i in range(0, len(starts), 16):
            out.append("            " + " ".join("%d," % v for v in starts[i:i + 16]) + "\n")
        out.append("        };\n")
        table_rows.append(f"            {{Enums::GameVersion::{group}, MOVES_{group}, STARTS_{group}, {len(blobs)}}},\n")
        print(f"  {group:<5} {resource:<14} {len(blobs):>5} entries {len(flat):>6} moves")

    out.append("""
        struct GroupTable
        {
            Enums::GameVersion group;
            const LevelUpMove *moves;
            const uint32_t *starts; // entry i spans starts[i] .. starts[i + 1]
            uint32_t entryCount;
        };
        const GroupTable TABLES[] = {
""")
    out.extend(table_rows)
    out.append("""        };
    }

    LevelUpList getLevelUpMoves(Enums::GameVersion group, uint16_t species, uint8_t form)
    {
        for (const GroupTable &table : TABLES)
        {
            if (table.group != group)
                continue;
            // PKHeX's PersonalTable.GetFormIndex, through the group's own personal row.
            const PersonalRecord &base = getPersonalRecord(group, species, 0);
            uint32_t index = species;
            if (form != 0 && base.formIndex != 0 && form < base.formCount)
                index = static_cast<uint32_t>(base.formIndex) + form - 1;
            if (index >= table.entryCount)
                return {};
            return {table.moves + table.starts[index], static_cast<uint16_t>(table.starts[index + 1] - table.starts[index])};
        }
        return {};
    }

    int getWildMoveset(Enums::GameVersion group, uint16_t species, uint8_t form, uint8_t level, uint16_t out[4])
    {
        // The games fill a wild Pokemon's moves by walking its level-up list in order and keeping the
        // last four distinct moves learned at or below its level (a move learnt twice is not doubled).
        const LevelUpList list = getLevelUpMoves(group, species, form);
        int count = 0;
        for (uint16_t i = 0; i < list.count; ++i)
        {
            const LevelUpMove &m = list.moves[i];
            if (m.level > level || m.move == 0)
                continue;
            if (std::find(out, out + count, m.move) != out + count)
                continue;
            if (count < 4)
                out[count++] = m.move;
            else
            {
                std::rotate(out, out + 1, out + 4);
                out[3] = m.move;
            }
        }
        return count;
    }
}
""")
    with open(source, "w") as fh:
        fh.writelines(out)
    with open(header, "w") as fh:
        fh.write("""// GENERATED by tools/gen_levelup.py from PKHeX level-up learnsets. Do not edit.
#ifndef PKM_LEVEL_UP_TABLE_H
#define PKM_LEVEL_UP_TABLE_H

#include <cstdint>

#include "Enums/GameVersion.h"

namespace Pokemon
{
    struct LevelUpMove
    {
        uint16_t move;
        uint8_t level; // 0 = learnt on evolution (Gen 7+), 1 = known from the start
    };

    /// A (species, form)'s level-up moves in one game, in learn order. Empty when PKSE has no table
    /// for the group (Gen 1/2) or the game has no such species.
    struct LevelUpList
    {
        const LevelUpMove *moves = nullptr;
        uint16_t count = 0;
    };

    LevelUpList getLevelUpMoves(Enums::GameVersion group, uint16_t species, uint8_t form);

    /// The moves a wild one of `level` knows in that game: the last four distinct level-up moves at or
    /// below the level. Writes up to four into `out` and returns how many.
    int getWildMoveset(Enums::GameVersion group, uint16_t species, uint8_t form, uint8_t level, uint16_t out[4]);
}

#endif
""")
    print(f"\n{len(GROUPS)} groups, {total} level-up moves, from PKHeX {pkhex_ref()}.")


if __name__ == "__main__":
    main()
